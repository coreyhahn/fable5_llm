class _StubW(object):
    def matvec(self, wbase, nrows, sh, ng, g, x8, w8=False, chan=None):
        return np.arange(nrows, dtype=np.int64) + 7 * (chan or 0)

    def _lookup(self, wbase, chan=None):
        return 0, 0, {"stride": 64}, 0


NROWS = 4
SHAPE = HW.shape_word(NROWS, 0, 1)


def movx(c):
    return SF.Rec(SF.OP_MOVX, flags=(c << SF.CHAN_SHIFT), addr_lo=0,
                  len_or_addr_hi=128)


def mvgo(c):
    return SF.Rec(SF.OP_MVGO, flags=(c << SF.CHAN_SHIFT),
                  target=SF.MVGO_NOWAIT, imm32=SHAPE,
                  addr_lo=HW.W_BASE & 0xFFFFFFFF,
                  len_or_addr_hi=((NROWS << 8) | ((HW.W_BASE >> 32) & 0xFF)))


def movy(c, dst=256):
    return SF.Rec(SF.OP_MOVY, target=c, addr_lo=dst, len_or_addr_hi=NROWS)


def fence(mask=0):
    return SF.Rec(SF.OP_FENCE, target=mask)


HALT = SF.Rec(SF.OP_HALT)
HAS_CAPS = "caps" in inspect.signature(SM.SeqExec.__init__).parameters


def run_model(recs, caps):
    """-> the finished SeqExec.  Raises what the model raises."""
    if HAS_CAPS:
        return SM.SeqExec(list(recs), b"", _StubW(), caps=caps).run()
    real = SF.validate

    def at_caps(r, **k):
        k.setdefault("caps", caps)
        return real(r, **k)
    SF.validate = at_caps
    try:
        return SM.SeqExec(list(recs), b"", _StubW()).run()
    finally:
        SF.validate = real


def refused(recs, caps=R1):
    """-> (refused by RunningChannelError, detail)."""
    try:
        run_model(recs, caps)
        return False, "ACCEPTED (today's FENCE clears every channel)"
    except SM.RunningChannelError as e:
        return True, f"RunningChannelError: {e}"


def accepted(recs, caps=R1):
    ex = run_model(recs, caps)
    return True, f"accepted; running after = {sorted(ex.running)}"


def state_of(ex):
    return (sorted(ex.running), dict(ex.stats), SM.snapshot(ex.M),
            {c: np.asarray(v).tolist() for c, v in ex.xwin.items()},
            {c: np.asarray(v).tolist() for c, v in ex.res.items()})


def same_state(a, b):
    d = SM.diff_state(a[2], b[2])
    return (a[0] == b[0] and a[1] == b[1] and not d and a[3] == b[3]
            and a[4] == b[4]), d


