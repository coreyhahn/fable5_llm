def synthetic2():
    """Two channels: a SHORT stream on ch0 and a LONG one on ch1, one global
    FENCE; ch0's result feeds a long VN.  At r0 the VN waits for ch1's long
    stream; at r1 a FENCE 0b0001 lets it overlap it (a mask that is a
    PROPER subset of the pending set)."""
    def mx(c):
        return SF.Rec(SF.OP_MOVX, flags=(c << SF.CHAN_SHIFT), addr_lo=0x100,
                      len_or_addr_hi=128)

    def mg(c):
        return SF.Rec(SF.OP_MVGO, flags=(c << SF.CHAN_SHIFT),
                      target=SF.MVGO_NOWAIT, imm32=SHAPE,
                      addr_lo=HW.W_BASE & 0xFFFFFFFF,
                      len_or_addr_hi=(NROWS << 8))

    def my(c, dst):
        return SF.Rec(SF.OP_MOVY, flags=SF.MOVY_MODE_BIT, target=c,
                      addr_lo=dst, len_or_addr_hi=NROWS)

    def arg(t, v):
        return SF.Rec(SF.OP_CSRWR, target=t, imm32=v)
    recs = [
        SF.Rec(SF.OP_CSRWR, target=SF.CSR_SEQ_TCNT, imm32=2),   # 0
        SF.Rec(SF.OP_EMB, addr_lo=0x100, len_or_addr_hi=128),   # 1
        mx(0), mx(1),                                           # 2 3
        mg(0), mg(1),                                           # 4 5
        SF.Rec(SF.OP_FENCE),                                    # 6
        my(0, 0x400),                                           # 7
        arg(SF.CSR_L_ARG0, 6 << 2),                             # 8 VN x64
        arg(SF.CSR_L_ARG1, GLS.enc_a1(0x400, 0x900)),           # 9
        arg(SF.CSR_L_ARG2, 0),                                  # 10
        SF.Rec(SF.OP_CMD, imm32=1),                             # 11
        my(1, 0x500),                                           # 12
        SF.Rec(SF.OP_JMP, flags=SF.JMP_TCNT, imm32=1),          # 13
        SF.Rec(SF.OP_HALT),                                     # 14
    ]
    S = {4: (0, 200), 5: (1, 3000)}
    dur = {SF.OP_EMB: 200, SF.OP_MOVX: 100, SF.OP_MVGO: 10,
           SF.OP_MOVY: 50, SF.OP_CSRWR: 5, SF.OP_CMD: 2000, SF.OP_JMP: 3}
    rows, t, ends = {}, 0, []
    for pc in range(1, 14):
        o = recs[pc].opcode
        cls = [0] * 16
        if o == SF.OP_MVGO:
            c, s = S[pc]
            cls[OC.BSY0 + c] = s
            ends.append(t + dur[o] + s)
        d = (max(ends) + 40 - t) if o == SF.OP_FENCE else dur[o]
        rows[pc] = (o, t, d, cls)
        t += d
    return recs, rows, [[11, 0x400, 4]]


def pending_walk(recs):
    """-> (every FENCE mask non-empty and a subset of the pending channels,
    [mask per FENCE], detail)."""
    pend, masks, bad = set(), [], []
    for i, r in enumerate(recs):
        if r.opcode == SF.OP_MVGO and r.target & SF.MVGO_NOWAIT:
            pend.add(r.chan)
        elif r.opcode == SF.OP_FENCE:
            m = r.target & 0xF
            masks.append(m)
            chans = set(range(4)) if m == 0 else {c for c in range(4)
                                                   if (m >> c) & 1}
            if m == 0 or not chans <= pend:
                bad.append((i, m, sorted(pend)))
            pend -= chans
    return not bad, masks, (f"bad {bad[:3]}" if bad else "")


def refused_at_empty(recs):
    try:
        SF.validate_stream(recs)
        return False
    except SF.SeqValidationError:
        return True


def pass_cases():
    print("=== the pass at r1 (ref/scripts/reorder_e4.py --rtl r1)")
    has_rtl = "rtl" in inspect.signature(RE.reorder).parameters
    print(f"    reorder(..., rtl=) {'PRESENT' if has_rtl else 'ABSENT'}")
    for label, mk in (("_synthetic", lambda: RE._synthetic()),
                      ("synthetic2", synthetic2)):
        for form in ("A", "B"):
            def f(label=label, mk=mk, form=form):
                recs, rows, cps = mk()
                n0, _c0, r0 = RE.reorder(recs, lambda k, lo, hi: rows, form,
                                         cps, rtl="r0")
                recs, rows, cps = mk()
                n1, _c1, r1 = RE.reorder(recs, lambda k, lo, hi: rows, form,
                                         cps, rtl="r1")
                s0, s1 = r0["segments"][0], r1["segments"][0]
                ok_sub, masks, det = pending_walk(n1)
                carry = bool(masks) and all(m != 0 for m in masks)
                le = s1["replay_mk"] <= s0["replay_mk"]
                timed = 0 <= s1["replay_mk"] - s1["sched_mk"] <= s1["jmp_win"]
                SF.validate_stream(n1, caps=R1)
                ref0 = refused_at_empty(n1)
                RE.assert_no_pending_hazard(n1, "r1 OUTPUT")
                names = " ".join(
                    (f"FENCE/{r.target:04b}" if r.opcode == SF.OP_FENCE
                     else SF.OP_NAME[r.opcode]) for r in n1)
                strict = True
                if label == "synthetic2":
                    # the point of R1: a proper-subset mask, and a shorter
                    # makespan than the global drain
                    strict = (0b0001 in masks
                              and s1["replay_mk"] < s0["replay_mk"])
                ok = (ok_sub and carry and le and timed and ref0 and strict
                      and s1["post_replay"][0] > 0)
                return ok, (f"masks {[bin(m) for m in masks]}; replay r1 "
                            f"{s1['replay_mk']} <= r0 {s0['replay_mk']}: {le}; "
                            f"r1 replay - sched {s1['replay_mk'] - s1['sched_mk']}"
                            f" (JMP win {s1['jmp_win']}); valid at {{R1}}, "
                            f"refused at {{}}: {ref0}; postcheck "
                            f"{s1['post_replay'][0]} edges; {det} | {names}")
            guarded("f", f"{label} form {form}: masked fences, <= r0, masks "
                         f"within the pending set, R1-only valid", f)

    def manifest():
        recs, rows, cps = RE._synthetic()
        tmp = tempfile.mkdtemp(prefix="sr4_tdd_")
        try:
            src = os.path.join(tmp, "src.e4")
            stream = SF.pack_stream(recs)
            open(src + ".seq", "wb").write(stream)
            open(src + ".seqdata.bin", "wb").write(b"\0" * 64)
            json.dump({"stream_sha256": hashlib.sha256(stream).hexdigest(),
                       "nrec": len(recs)}, open(src + ".seq.json", "w"))
            got = {}
            for rtl in ("r0", "r1"):
                recs, rows, cps = RE._synthetic()
                new, ncps, rep = RE.reorder(recs, lambda k, lo, hi: rows, "B",
                                            cps, rtl=rtl)
                out = os.path.join(tmp, f"out_{rtl}.e4")
                RE.write_out(out, src, new, ncps, rep)
                m = json.load(open(out + ".seq.json"))
                got[rtl] = (m.get("seq_isa"), m.get("caps"))
            ok = got["r1"] == ("2.3", ["R1"]) and got["r0"] == (None, None)
            return ok, f"manifest (seq_isa, caps): {got}"
        finally:
            shutil.rmtree(tmp)
    guarded("f", "write_out: r1 records seq_isa 2.3 + caps [R1]; r0 nothing new",
            manifest)

    def refuse_masked_input():
        recs, rows, cps = synthetic2()
        recs[6] = SF.Rec(SF.OP_FENCE, target=0b0011)
        try:
            RE.reorder(recs, lambda k, lo, hi: rows, "B", cps, rtl="r1")
            return False, "reordered a stream that already carries masks"
        except RE.ReorderError as e:
            return True, f"ReorderError: {e}"
    guarded("f", "the pass refuses an input whose FENCEs are already masked "
                 "(OV1's stream_durations assumes the global drain)",
            refuse_masked_input)

    # SR11b fix round 1 (ownership granted for this case only): SR11b
    # landed --rtl r2, so the case that required it REFUSED is replaced 1:1
    # by its successor — r2 is accepted, its output validates at caps
    # {R1,R2} and is REFUSED at {R1} (an R1 bitstream ignores the banks,
    # SEQ_ISA v2.3 B17.2).
    def r2_admission():
        recs, rows, cps = RE._synthetic()
        new, _c, _rep = RE.reorder(recs, lambda k, lo, hi: rows, "B", cps,
                                   rtl="r2")
        SF.validate_stream(new, caps=frozenset({"R1", "R2"}))
        try:
            SF.validate_stream(new, caps=R1)
            return False, "the r2 output validated at {R1}"
        except SF.SeqValidationError as e:
            return True, (f"r2 accepted; valid at {{R1,R2}}; refused at "
                          f"{{R1}}: {e}")
    guarded("f", "--rtl r2 accepted (SR11b): valid at caps {R1,R2}, refused "
                 "at {R1}", r2_admission)


